#!/usr/bin/env bash
# GREEN probe for REQ-730: the report catalog lists each bundle's second-opinion pages.
# Checks whichever tree it runs in. Expected to FAIL at base: the two new tests do not exist
# and the tracked catalog has no second_opinions field.
set -euo pipefail
root="$(git rev-parse --show-toplevel)"
cd "$root"

fail() { printf 'REQ-730 probe FAIL: %s\n' "$*" >&2; exit 1; }

# 1. The new tests and every existing catalog, organize and banner test pass (a skip is not a pass).
go_output="$(cd skills/do-work/tools/do-work-cli && go test -count=1 -v \
  -run '^(TestAIReportIndex|TestAIReportOrganize|TestSecondOpinionBanner)' ./internal/toolboxcommands/ 2>&1)" \
  || fail "catalog tests failed: $go_output"
for test_name in TestAIReportIndexListsSecondOpinionPagesUnderTheirBundle TestAIReportIndexListsPlainSecondOpinionPageByFileName \
  TestAIReportIndexCatalogsEveryBundleNamingStyleOnce TestAIReportIndexLinksSupersededProposalToSuccessor \
  TestAIReportIndexFindListsMatchesNewestFirstIncludingSuperseded TestAIReportIndexRefusesHandMadeCatalog \
  TestAIReportIndexReadsBundlesInsideMonthFolders; do
  grep -qF -- "--- PASS: $test_name " <<<"$go_output" || fail "$test_name did not PASS"
done
if grep -qE -- '--- (FAIL|SKIP):' <<<"$go_output"; then fail "a catalog test failed or skipped: $go_output"; fi

# 2. The tracked catalog pair was regenerated by the new code (D-03): the real bundle with three
#    tree pages lists them in catalog.json and links them from ai-reports/index.html.
bundle='2026-11-14_1547_proposal-tinka-review-surface'
page='index-v1c03-claude-claude-fable-5-2-custom-zoomable-relation-map.html'
catalog="$(cat ai-reports/catalog.json)"
grep -qF '"second_opinions"' <<<"$catalog" || fail 'ai-reports/catalog.json has no second_opinions field'
grep -qF "\"ai-reports/$bundle/$page\"" <<<"$catalog" || fail "catalog.json does not list $page"
grep -qF '"v1c03"' <<<"$catalog" || fail 'catalog.json does not carry the v1c03 tree id'
index_page="$(cat ai-reports/index.html)"
grep -qF "href=\"$bundle/$page\"" <<<"$index_page" || fail "ai-reports/index.html does not link $page"

# 3. No bundle file changed against the merge base with main (the catalog never writes into bundles).
base="$(git merge-base HEAD main 2>/dev/null || git rev-parse HEAD)"
changed_bundle_files="$(git diff --name-only "$base" -- ai-reports/ ':(exclude)ai-reports/catalog.json' ':(exclude)ai-reports/index.html')"
[ -z "$changed_bundle_files" ] || fail "bundle files changed: $changed_bundle_files"

printf 'REQ-730 probe PASS\n'
